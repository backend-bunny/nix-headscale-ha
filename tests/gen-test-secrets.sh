#!/usr/bin/env bash
# tests/gen-test-secrets.sh
#
# One-shot bootstrap script that:
#
#   1. Generates the headscale-ha cluster mTLS PKI (CA + per-node certs).
#   2. Assembles a secrets.yaml from the generated PKI plus prompts for
#      Cloudflare and Backblaze B2 credentials.
#   3. Encrypts secrets.yaml with SOPS (using the key_groups in .sops.yaml).
#
# The resulting tests/secrets.yaml can be committed to git (it is safely
# encrypted) and used by:
#   • sops-nix / agenix on production NixOS nodes (extracts individual keys)
#   • tests/run-e2e.sh --decrypt (injects real B2/CF creds into the e2e test)
#
# USAGE
#   ./tests/gen-test-secrets.sh [OPTIONS]
#
# OPTIONS
#   --nodes SPEC   Comma-separated list of "name:IP" pairs for PKI generation.
#                  Default: node1:192.168.1.11,node2:192.168.1.12,node3:192.168.1.13
#
#   --no-encrypt   Write tests/secrets.yaml in plaintext (DO NOT COMMIT).
#                  Useful for inspecting the output format.
#
#   --force        Overwrite an existing tests/secrets.yaml without prompting.
#
#   --pki-dir DIR  Use an existing PKI directory instead of generating new certs.
#                  The directory must contain ca.crt, ca.key, and <name>.crt /
#                  <name>.key for each node.
#
#   --help         Show this message.
#
# PREREQUISITES
#   • openssl
#   • sops (unless --no-encrypt)
#   • age key configured in .sops.yaml (unless --no-encrypt)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# Defaults
NODES_SPEC="node1:192.168.1.11,node2:192.168.1.12,node3:192.168.1.13"
NO_ENCRYPT=false
FORCE=false
PKI_DIR=""

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --nodes)      NODES_SPEC="$2"; shift ;;
    --no-encrypt) NO_ENCRYPT=true ;;
    --force)      FORCE=true ;;
    --pki-dir)    PKI_DIR="$2"; shift ;;
    --help|-h)
      sed -n '3,45p' "${BASH_SOURCE[0]}" | sed 's/^# \?//'
      exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
  shift
done

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info()  { echo -e "${GREEN}[gen-secrets]${NC} $*"; }
warn()  { echo -e "${YELLOW}[gen-secrets]${NC} $*"; }
error() { echo -e "${RED}[gen-secrets]${NC} $*" >&2; }
step()  { echo -e "${CYAN}[gen-secrets]${NC} $*"; }

# ── Guard: don't overwrite without --force ───────────────────────────────────
SECRETS_OUT="$SCRIPT_DIR/secrets.yaml"
if [[ -f "$SECRETS_OUT" ]] && ! $FORCE; then
  error "tests/secrets.yaml already exists.  Use --force to overwrite."
  exit 1
fi

# ── Step 1: Generate PKI ──────────────────────────────────────────────────────
step "Step 1/4 — Generate cluster mTLS PKI"

TMPDIR="$(mktemp -d)"
trap 'rm -rf "$TMPDIR"' EXIT

if [[ -n "$PKI_DIR" ]]; then
  info "Using existing PKI directory: $PKI_DIR"
  if [[ ! -f "$PKI_DIR/ca.crt" ]]; then
    error "PKI directory must contain ca.crt"; exit 1
  fi
  GENERATED_PKI="$PKI_DIR"
else
  GENERATED_PKI="$TMPDIR/pki"
  PKI_DIR_ENV="$GENERATED_PKI" bash "$REPO_ROOT/scripts/gen-cluster-certs.sh" \
    $(echo "$NODES_SPEC" | tr ',' ' ')
fi

# Parse node names from the spec
IFS=',' read -ra NODE_SPECS <<< "$NODES_SPEC"

# Helper: indent a PEM block with 4 spaces for YAML block scalar
indent_pem() {
  sed 's/^/    /'
}

# ── Step 2: Collect Cloudflare + B2 credentials ───────────────────────────────
step "Step 2/4 — Collect Cloudflare and Backblaze B2 credentials"
echo ""
echo "  Leave a value blank to use the placeholder (you can edit the"
echo "  encrypted file later with: sops tests/secrets.yaml)"
echo ""

read_cred() {
  local prompt="$1" default="${2:-}"
  local val
  if [[ -n "$default" ]]; then
    read -rp "  $prompt [$default]: " val
    echo "${val:-$default}"
  else
    read -rp "  $prompt: " val
    echo "$val"
  fi
}

CF_API_TOKEN="$(read_cred    "Cloudflare API token (DNS:Edit)"     "${E2E_CF_API_TOKEN:-}")"
CF_ZONE_ID="$(read_cred      "Cloudflare Zone ID"                  "${E2E_CF_ZONE_ID:-}")"
CF_RECORD_NAME="$(read_cred  "Headscale DNS record (FQDN)"         "${E2E_CF_RECORD_NAME:-headscale.example.com}")"
B2_KEY_ID="$(read_cred       "Backblaze B2 Key ID (or S3 key ID)"  "${E2E_B2_KEY_ID:-}")"
B2_APP_KEY="$(read_cred      "Backblaze B2 Application Key"        "${E2E_B2_APP_KEY:-}")"
B2_BUCKET="$(read_cred       "Backblaze B2 bucket name"            "${E2E_B2_BUCKET:-headscale-ha}")"
B2_ENDPOINT="$(read_cred     "S3 endpoint URL"                     "${E2E_B2_ENDPOINT:-https://s3.us-west-002.backblazeb2.com}")"
echo ""

# ── Step 3: Assemble secrets.yaml ─────────────────────────────────────────────
step "Step 3/4 — Assemble secrets.yaml"

{
  cat <<'YAML_HEADER'
# This file is SOPS-encrypted.  Edit with: sops tests/secrets.yaml
# Generated by tests/gen-test-secrets.sh — do not edit the plaintext copy.

YAML_HEADER

  # ── Cluster CA ────────────────────────────────────────────────────────────
  echo "cluster:"
  echo "  ca_cert: |"
  cat "$GENERATED_PKI/ca.crt" | indent_pem
  echo "  ca_key: |"
  cat "$GENERATED_PKI/ca.key" | indent_pem
  echo ""

  # ── Per-node certs + keys ──────────────────────────────────────────────────
  echo "nodes:"
  for spec in "${NODE_SPECS[@]}"; do
    name="${spec%%:*}"
    echo "  $name:"
    echo "    cert: |"
    cat "$GENERATED_PKI/${name}.crt" | indent_pem
    echo "    key: |"
    cat "$GENERATED_PKI/${name}.key" | indent_pem
  done
  echo ""

  # ── Litestream ────────────────────────────────────────────────────────────
  cat <<YAML_LITESTREAM
litestream:
  b2_key_id: ${B2_KEY_ID:-REPLACE_WITH_B2_KEY_ID}
  b2_application_key: ${B2_APP_KEY:-REPLACE_WITH_B2_APPLICATION_KEY}
  b2_bucket: ${B2_BUCKET:-headscale-ha}
  b2_endpoint: ${B2_ENDPOINT:-https://s3.us-west-002.backblazeb2.com}
  env_file: |
    LITESTREAM_ACCESS_KEY_ID=${B2_KEY_ID:-REPLACE_WITH_B2_KEY_ID}
    LITESTREAM_SECRET_ACCESS_KEY=${B2_APP_KEY:-REPLACE_WITH_B2_APPLICATION_KEY}

YAML_LITESTREAM

  # ── Cloudflare ────────────────────────────────────────────────────────────
  cat <<YAML_CF
cloudflare:
  api_token: ${CF_API_TOKEN:-REPLACE_WITH_CLOUDFLARE_API_TOKEN}
  zone_id: ${CF_ZONE_ID:-REPLACE_WITH_CLOUDFLARE_ZONE_ID}
  record_name: ${CF_RECORD_NAME:-headscale.example.com}
  caddy_env_file: |
    CLOUDFLARE_DNS_API_TOKEN=${CF_API_TOKEN:-REPLACE_WITH_CLOUDFLARE_API_TOKEN}
  watchdog_env_file: |
    CLOUDFLARE_DNS_API_TOKEN=${CF_API_TOKEN:-REPLACE_WITH_CLOUDFLARE_API_TOKEN}
YAML_CF

} > "$TMPDIR/secrets.yaml"

# ── Step 4: Encrypt with SOPS ─────────────────────────────────────────────────
step "Step 4/4 — Encrypt with SOPS"

if $NO_ENCRYPT; then
  warn "--no-encrypt: writing plaintext YAML.  DO NOT commit this file."
  cp "$TMPDIR/secrets.yaml" "$SECRETS_OUT"
  info "Wrote (plaintext): $SECRETS_OUT"
else
  if ! command -v sops >/dev/null 2>&1; then
    error "sops not found.  Install with: nix shell nixpkgs#sops"
    error "Or run with --no-encrypt to write a plaintext draft."
    exit 1
  fi

  # Check .sops.yaml exists and has actual keys
  SOPS_YAML="$REPO_ROOT/.sops.yaml"
  if [[ ! -f "$SOPS_YAML" ]]; then
    error ".sops.yaml not found at $SOPS_YAML"
    error "Run: cp .sops.yaml.example .sops.yaml  and set your age public key."
    exit 1
  fi
  if grep -q "age1REPLACE_ME" "$SOPS_YAML"; then
    error ".sops.yaml still has the placeholder age key."
    error "Edit $SOPS_YAML and replace 'age1REPLACE_ME...' with your actual public key."
    error "(Generate one with: age-keygen -o ~/.config/sops/age/keys.txt)"
    exit 1
  fi

  sops --encrypt --config "$SOPS_YAML" "$TMPDIR/secrets.yaml" > "$SECRETS_OUT"
  info "Encrypted secrets written to: $SECRETS_OUT"
fi

# ── Summary ───────────────────────────────────────────────────────────────────
echo ""
info "========================================================"
info " Cluster PKI + secrets generated successfully."
info "========================================================"
echo ""
echo "  Next steps:"
echo ""
echo "  1. Commit tests/secrets.yaml to git (it is safely encrypted)."
echo "     git add tests/secrets.yaml && git commit -m 'chore: add encrypted cluster secrets'"
echo ""
echo "  2. Run the e2e test (hermetic, no real credentials needed):"
echo "     ./tests/run-e2e.sh"
echo ""
echo "  3. Run the e2e test with real B2 / Cloudflare credentials:"
echo "     ./tests/run-e2e.sh --decrypt"
echo ""
echo "  4. Reference secrets in production NixOS configs:"
echo "     sops.secrets.\"le-node1-key\" = {"
echo "       sopsFile = ./tests/secrets.yaml;"
echo "       key      = \"nodes/node1/key\";"
echo "       path     = \"/run/secrets/le-node1.key\";"
echo "     };"
echo ""
echo "  PKI validity: 2 years.  Re-run this script to rotate."
echo "  CA validity:  10 years. Pass --pki-dir <existing-pki> to reuse the CA."
echo ""
